/**
 * Generates src/compat/i18n-dict.ts from the engine's English locale.
 *
 * The ported widget components call `t("ui.chat.mochiPrivateChat.…")` — the
 * engine's own keys. SillyTavern's locale files do not contain them, so the
 * English source strings are lifted verbatim out of the engine locale once and
 * shipped with the extension. Run with:
 *   node scripts/generate-i18n.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENGINE_LOCALE =
  'D:/OpenCodeProjects/Dori-Engine/packages/client/src/localization/locales/en.json';

if (!fs.existsSync(ENGINE_LOCALE)) {
  console.error(`engine locale not found at ${ENGINE_LOCALE} — nothing to generate`);
  process.exit(1);
}

/** Keys the ported components reference, plus the surface the new shell needs. */
const PREFIXES = ['ui.chat.mochiosview.', 'ui.chat.mochiPrivateChat.', 'ui.chat.mochiGroupChat.', 'chat.toolbar.mochiOs', 'ui.game.gamesessionhistory.maps', 'game.toolbar.volume.music', 'extensions.contributions.tools', 'ui.agents.agenteditor.files', 'ui.chat.homeprofessormarichat.attachChatHistoryRangePrefix'];

const locale = JSON.parse(fs.readFileSync(ENGINE_LOCALE, 'utf8'));
const flat = new Map();
const walk = (node, prefix) => {
  for (const [key, value] of Object.entries(node)) {
    const full = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object') walk(value, full);
    else flat.set(full, String(value));
  }
};
walk(locale, '');

const wanted = [...flat.keys()]
  .filter((key) => PREFIXES.some((prefix) => key === prefix || key.startsWith(prefix)))
  .sort();

/** Keys the extension defines itself because they describe SillyTavern, not the engine. */
const LOCAL = {
  'mochi.st.title': 'Mochi OS',
  'mochi.st.open': 'Open Mochi OS',
  'mochi.st.close': 'Close Mochi OS',
  'mochi.st.noChat': 'Open a chat first',
  'mochi.st.noChatHint': 'Mochi OS belongs to a chat. Pick a character or start a group to build a phone for them.',
  'mochi.st.settings': 'Mochi OS settings',
  'mochi.st.settingsHint': 'How the phone behaves inside SillyTavern.',
  'mochi.st.generating': 'Generating…',
  'mochi.st.stop': 'Stop',
  'mochi.st.regenerate': 'Regenerate',
  'mochi.st.reply': 'Reply',
  'mochi.st.send': 'Send',
  'mochi.st.typeMessage': 'Write a message…',
  'mochi.st.continue': 'Continue without replying',
  'mochi.st.deleteThread': 'Delete this thread',
  'mochi.st.exportYaml': 'Copy YAML',
  'mochi.st.importYaml': 'Paste YAML',
  'ui.chat.mochiosview.editAndConfirmYamlShort': 'Edit YAML',
  'ui.chat.mochiosview.deleteThreadShort': 'Delete thread',
  'mochi.st.storage': 'Stored in this chat’s metadata',
  'mochi.st.storageHint': 'The phone travels with the chat: exporting, importing or branching the chat carries it along.',
  'mochi.st.generateData': 'Generate phone data',
  'mochi.st.noData': 'No phone data yet',
  'mochi.st.noDataHint': 'Generate the contacts, groups and your profile from this chat’s character.',
  'mochi.st.groupMembers': 'Members',
  'mochi.st.creatingThread': 'Creating…',
  'mochi.st.archivedTurns': 'Archived turns',
  'mochi.st.trimHint': 'Older turns are dropped from the archive when it grows past this many.',
  'mochi.st.availableSoon': 'Needs the Mochi OS server',
  'mochi.st.availableSoonHint': 'This app is backed by a Mochi OS backend that a SillyTavern extension cannot run. Everything else on the phone works.',
};

const entries = [...wanted.map((key) => [key, flat.get(key)]), ...Object.entries(LOCAL)]
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join('\n');

const out = `/**
 * English strings for the extension, generated by scripts/generate-i18n.mjs.
 *
 * The ported widgets keep the engine's translation keys so the components
 * themselves needed no changes. Those keys do not exist in SillyTavern's
 * locale files, so their English source text lives here instead. Edits to this
 * file are overwritten by the generator; change the engine locale or add
 * extension-owned keys in scripts/generate-i18n.mjs.
 */
export const EN_DICT: Record<string, string> = {
${body}
};
`;

const target = path.join(root, 'src', 'compat', 'i18n-dict.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${entries.length} strings to ${path.relative(root, target)}`);